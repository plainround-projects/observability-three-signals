-- 001_schema.sql: DDL for the orders database. Safe to run again.
-- Run with: make db   (psql variable reader_password comes from ORDERS_READER_PASSWORD)

CREATE TABLE IF NOT EXISTS orders (
    id            integer     PRIMARY KEY,
    customer_name text        NOT NULL,
    placed_at     timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE orders IS 'One row per order; the back service reads it with SELECT id, customer_name.';

CREATE TABLE IF NOT EXISTS order_items (
    id               bigint  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id         integer NOT NULL REFERENCES orders (id),
    sku              text    NOT NULL,
    quantity         integer NOT NULL CHECK (quantity > 0),
    unit_price_cents integer NOT NULL CHECK (unit_price_cents >= 0)
);
COMMENT ON TABLE order_items IS 'The lines of an order; 1 to 5 per order in the seed data.';

-- The back service looks items up by order id, so the lookup must be an index scan, never a table scan.
CREATE INDEX IF NOT EXISTS order_items_order_id_idx ON order_items (order_id);

-- Least privilege: the back service connects as a role that can read these two tables and nothing else.
SELECT format('CREATE ROLE orders_reader LOGIN PASSWORD %L', :'reader_password')
WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'orders_reader')
\gexec
SELECT format('ALTER ROLE orders_reader LOGIN PASSWORD %L', :'reader_password')
\gexec
GRANT CONNECT ON DATABASE orders TO orders_reader;
GRANT USAGE ON SCHEMA public TO orders_reader;
GRANT SELECT ON orders, order_items TO orders_reader;
